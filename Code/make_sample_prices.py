"""
Generate Data/ipa_prices.sample.json — a SYNTHETIC monthly IPA price series.

The real price series used in the course project is not distributed with this
repository. This script writes a deterministic stand-in with the same format and
period (2012-01 to 2024-12, 156 months) so the pipeline and tests can run.
The numbers are made up: a slow cycle, an annual season and AR(1) noise.

Usage:
    python make_sample_prices.py
"""

from __future__ import annotations

import json
import os

import numpy as np

SEED = 20260101
START_YEAR, END_YEAR = 2012, 2024
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'Data', 'ipa_prices.sample.json')


def make_series(seed: int = SEED) -> list[dict]:
    rng = np.random.default_rng(seed)
    months = [(y, m) for y in range(START_YEAR, END_YEAR + 1) for m in range(1, 13)]
    t = np.arange(len(months))
    noise = np.zeros(len(t))
    for i in range(1, len(t)):
        noise[i] = 0.8 * noise[i - 1] + rng.normal(0.0, 1.2)
    price = 42.0 + 6.0 * np.sin(2 * np.pi * t / 96.0) + 1.5 * np.sin(2 * np.pi * t / 12.0) + noise
    price = np.clip(price, 25.0, 60.0)
    return [{'date': f'{y:04d}-{m:02d}', 'price': round(float(p), 1)} for (y, m), p in zip(months, price)]


def main() -> None:
    payload = {
        'description': 'SYNTHETIC demonstration data, NOT real IPA prices. '
                       'Generated by make_sample_prices.py so the pipeline can run without the private data.',
        'synthetic': True,
        'unit': 'TWD/KG',
        'generator': {'script': 'make_sample_prices.py', 'seed': SEED},
        'prices': make_series(),
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write('\n')
    print(f"Wrote {len(payload['prices'])} synthetic monthly prices to {OUT}")


if __name__ == '__main__':
    main()
